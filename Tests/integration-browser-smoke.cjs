  fs.mkdirSync(output, { recursive: true });
  const owner = await request.newContext({ baseURL: base, extraHTTPHeaders: { Origin: base } });
  async function api(route, method = 'GET', data) {
    const response = await owner.fetch(route, { method, ...(data === undefined ? {} : { data }) });
    assert(response.ok(), `${method} ${route}: ${response.status()}`);
    return response.json();
  }
  const publicOffer = await api('/api/public/integrations/intelligent-golf');
  assert.equal(publicOffer.amountPence, 29900); assert.equal(publicOffer.billingInterval, 'year');
  assert.equal(publicOffer.currency, 'gbp'); assert.equal(publicOffer.available, false);
