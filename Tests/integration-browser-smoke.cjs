  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'integration-details-mobile.png'), fullPage: true });
  await page.goto(base + '/#pricing'); await offer.scrollIntoViewIfNeeded();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await offer.screenshot({ path: path.join(output, 'integration-pricing-mobile.png') });
