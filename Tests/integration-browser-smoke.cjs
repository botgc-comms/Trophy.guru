  assert.equal(await offer.locator('[data-ig-subscribe]').isVisible(), false);
  assert(await offer.evaluate(el => el.previousElementSibling.classList.contains('pricing-grid')));
  await page.locator('#pricing').screenshot({ path: path.join(output, 'integration-pricing-desktop.png') });
  await offer.getByRole('link', { name: /what.*integration|explore.*integration|see.*integration/i }).click();
  await page.waitForURL('**/integrations/intelligent-golf/');
  assert.equal(await page.locator('[data-ig-subscribe]').isVisible(), false);
