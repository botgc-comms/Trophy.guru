  await api('/api/auth/signup', 'POST', { displayName: 'Integration QA owner', email, password: 'FixturePassword123!' });
  const mail = fs.readdirSync(path.join(dataRoot, 'mail')).map(name => fs.readFileSync(path.join(dataRoot, 'mail', name), 'utf8')).find(text => text.includes(email));
  const token = mail.replace(/=\r?\n/g, '').replace(/=3D/g, '=').match(/#verify=([A-Za-z0-9_-]+)/)?.[1]; assert(token);
  await api('/api/auth/verify-email', 'POST', { token });
  await api('/api/club', 'PUT', { name: 'Integration QA Golf Club', sport: 'Golf', country: 'United Kingdom', website: 'https://club.example' });
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jx0sAAAAASUVORK5CYII=', 'base64');
  const logo = await owner.post('/api/club/logo', { multipart: { logo: { name: 'fixture.png', mimeType: 'image/png', buffer: png } } }); assert(logo.ok());
