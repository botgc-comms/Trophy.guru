  assert(await signedOffer.getByRole('button', { name: 'Coming soon' }).isDisabled());
  assert(await signedOffer.evaluate(el => el.previousElementSibling.classList.contains('billing-packs')));
  await signedOffer.screenshot({ path: path.join(output, 'integration-billing-desktop.png') });
  await account.setViewportSize({ width: 390, height: 844 });
